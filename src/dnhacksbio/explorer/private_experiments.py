"""Runner-owned registered submissions. Only public acknowledgements enter research history."""
from __future__ import annotations

import asyncio
import json
import os
from uuid import uuid4

from dnhacksbio.experiment_transport import send_payload, REQUEST_ID

METHODS = {
    "paired-pathway-v1": ("expression-experiment", "DNHACKS_EXPRESSION_ENDPOINT"),
    "dependency-chronos-v1": ("dependency-experiment", "DNHACKS_DEPENDENCY_ENDPOINT"),
    "biomarker_auc.v1": ("drug-response-experiment", "DNHACKS_DRUG_RESPONSE_ENDPOINT"),
}


async def dispatch(explorer, args):
    if not isinstance(args, dict) or set(args) != {"method_id", "spec", "input"}:
        return "(private experiment requires method_id, registered spec and input)"
    method = args["method_id"]
    if not isinstance(method, str) or method not in METHODS:
        return "(unsupported private experiment method)"
    skill, variable = METHODS[method]
    if skill not in explorer._delivered or skill not in explorer._skill_snapshots:
        return f"(get_skill {skill} before submitting)"
    endpoint = os.environ.get(variable)
    if not endpoint:
        return "(private experiment service is not configured)"
    data = args["input"]
    if (not isinstance(data, dict) or set(data) != {"cohort_id", "manifest_sha256"}
            or not isinstance(data["cohort_id"], str) or not REQUEST_ID.fullmatch(data["cohort_id"])
            or not isinstance(args["spec"], dict)):
        return "(use an operator-provided registered spec and cohort reference)"
    # IDs are generated by the runner, never taken from stdout or an agent-supplied run ID.
    expid = uuid4().hex
    payload = {"request_id": expid, "spec": args["spec"], "input": data}
    raw = json.dumps(payload, sort_keys=True, separators=(",", ":"), allow_nan=False)
    if len(raw.encode()) > 16384:
        return "(registered submission exceeds size limit)"
    explorer._event("private_experiment.requested", {
        "method_id": method, "receipt": expid, "request": explorer.journal.blob(raw)}, experiment_id=expid)
    # Shield the transport so cancellation does not leave an unaccounted live submission thread.
    task = asyncio.create_task(asyncio.to_thread(send_payload, payload, endpoint))
    try:
        receipt = await asyncio.shield(task)
    except asyncio.CancelledError:
        try:
            await task
        except Exception:
            pass
        raise
    except Exception:
        # The private collector reconciles ambiguous acknowledgements with the durable queue.
        return "(submission acknowledgement unavailable; private reconciliation required)"
    explorer._event("private_experiment.acknowledged", receipt, experiment_id=expid)
    return json.dumps(receipt)
